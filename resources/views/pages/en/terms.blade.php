<h2>5. Cancellation and no-show</h2>
<ul>
    <li>You may cancel free of charge from your tracking link up to the deadline shown on the Venue’s listing (in hours before the appointment). After that deadline, cancellation remains possible but the Venue may apply its own conditions.</li>
    <li>A Venue cannot cancel a confirmed booking on its own: it must submit a justified request, you are informed and may respond, then HammamLuxury decides. If a booking is cancelled at the Venue’s initiative, no fee is charged to you.</li>
    <li>If you do not show up without cancelling (“no-show”), the Venue may report it; repeated no-shows may limit your future requests.</li>
</ul>

